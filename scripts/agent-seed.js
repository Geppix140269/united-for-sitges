// Prints SQL that loads the source registry, the PROPOSED FAQ templates and
// a disabled forum channel. Everything is inactive and unapproved; a
// moderator must verify and approve each item in the agent console.
// Usage: node scripts/agent-seed.js > /tmp/agent-seed.sql  (review, then apply when authorised)
import { readFileSync } from 'node:fs';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a || []).map(q).join(',')}]::text[]`;
const sources = JSON.parse(readFileSync(new URL('../data/agent/sources.json', import.meta.url), 'utf8')).sources;
const faqs = JSON.parse(readFileSync(new URL('../data/agent/faq-seed.json', import.meta.url), 'utf8')).faq;

const out = ['-- Generated by scripts/agent-seed.js. Inactive and unapproved by design.', 'begin;'];
for (const s of sources) {
  out.push(`insert into ufs_agent.sources(slug,title,url,publisher,source_class,languages,categories,active,notes) values (${q(s.slug)},${q(s.title)},${q(s.url)},${q(s.publisher)},${q(s.source_class)},${arr(s.languages)},${arr(s.categories)},false,'seeded; requires human verification') on conflict (slug) do nothing;`);
}
for (const f of faqs) {
  out.push(`insert into ufs_agent.faq(slug,canonical_question,match_phrases,approved_answer,language,source_url,is_factual,allowed_channels,active) values (${q(f.slug)},${q(f.canonical_question)},${arr(f.match_phrases)},${q(f.approved_answer)},${q(f.language)},${q(f.source_url)},${f.is_factual ? 'true' : 'false'},${arr([])},false) on conflict (slug) do nothing;`);
}
out.push("insert into ufs_agent.channels(provider,external_account_id,account_label,connection_status,capabilities,ingest_enabled) values ('forum','unitedforsitges-forum','United for Sitges forum','verified','{\"reply\":false,\"publish\":false}'::jsonb,false) on conflict do nothing;");
out.push('commit;');
console.log(out.join('\n'));
